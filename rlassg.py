class SmartSchedulingEnv(gym.Env):

    def __init__(self):
        super().__init__()

        self.total_events = 10

        # Actions: 0 = Schedule, 1 = Reschedule, 2 = Cancel
        self.action_space = spaces.Discrete(3)

        # Observation: normalized event index, conflict indicator
        self.observation_space = spaces.Box(
            low=np.array([0.0, 0.0], dtype=np.float32),
            high=np.array([1.0, 1.0], dtype=np.float32),
            dtype=np.float32
        )

    def reset(self, seed=None, options=None):
        super().reset(seed=seed)

        self.current_event = 0

        # Generate 10 events; approximately 35% have conflicts
        self.conflicts = self.np_random.binomial(
            1, 0.35, size=self.total_events
        )

        self.unresolved_conflicts = 0
        self.cancelled_events = 0

        return self._get_obs(), {}

    def _get_obs(self):
        if self.current_event >= self.total_events:
            return np.array([1.0, 0.0], dtype=np.float32)

        return np.array([
            self.current_event / self.total_events,
            self.conflicts[self.current_event]
        ], dtype=np.float32)

    def step(self, action):
        conflict_before = int(self.conflicts[self.current_event])

        if action == 0:  # Schedule
            reward = 1.0

            if conflict_before:
                reward -= 2.0

        elif action == 1:  # Reschedule
            reward = 0.5
            self.conflicts[self.current_event] = 0

        else:  # Cancel
            reward = -1.0
            self.conflicts[self.current_event] = 0
            self.cancelled_events += 1

        conflict_after = int(self.conflicts[self.current_event])
        self.unresolved_conflicts += conflict_after

        self.current_event += 1

        terminated = self.current_event >= self.total_events
        truncated = False

        info = {
            "conflict_before": conflict_before,
            "conflict_after": conflict_after,
            "unresolved_conflicts": self.unresolved_conflicts,
            "cancelled_events": self.cancelled_events
        }

        return (
            self._get_obs(),
            reward,
            terminated,
            truncated,
            info
        )


