class ConflictRateEnv(SmartSchedulingEnv):
    def __init__(self, conflict_rate=0.35):
        super().__init__()
        self.conflict_rate = conflict_rate

    def reset(self, seed=None, options=None):
        obs, info = super().reset(seed=seed, options=options)

        # Generate conflicts at the selected rate
        self.conflicts = self.np_random.binomial(
            1, self.conflict_rate, size=self.total_events
        )
        self.unresolved_conflicts = 0
        self.cancelled_events = 0

        return self._get_obs(), info

