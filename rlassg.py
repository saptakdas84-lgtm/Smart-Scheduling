def evaluate_ppo(model, episodes=100):

    rewards = []
    conflicts = []
    cancellations = []

    test_env = SmartSchedulingEnv()

    for episode in range(episodes):

        obs, info = test_env.reset(seed=1000 + episode)

        episode_reward = 0
        done = False
        final_info = {}

        while not done:
            action, _ = model.predict(
                obs, deterministic=True
            )

            obs, reward, terminated, truncated, info = (
                test_env.step(int(action))
            )

            episode_reward += reward
            final_info = info
            done = terminated or truncated

        rewards.append(episode_reward)
        conflicts.append(final_info["unresolved_conflicts"])
        cancellations.append(final_info["cancelled_events"])

    return {
        "Average reward": np.mean(rewards),
        "Average unresolved conflicts": np.mean(conflicts),
        "Average cancellations": np.mean(cancellations),
        "Rewards": rewards,
        "Conflicts": conflicts
    }


